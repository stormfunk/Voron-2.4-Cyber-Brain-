def measure(s, h, track=0.14):
    """width in mm of `s` drawn at cap height h"""
    w = 0.0
    for ch in s:
        c = ch.upper()
        if c == '×':
            c = 'X_MUL'
        w += W.get(c, 0.55) * h + track * h
    if w > 0:
        w -= track * h
    return w


def text(s, x, y, h, track=0.14, align='left'):
    """polylines (lists of (x, y) mm tuples) for `s`, baseline at y.
    align: left | right | center - x is the corresponding edge."""
    total = measure(s, h, track)
    if align == 'right':
        x = x - total
    elif align in ('center', 'centre'):
        x = x - total / 2.0
    out = []
    cx = x
    for ch in s:
        c = ch.upper()
        if c == '×':
            c = 'X_MUL'
        gw = W.get(c, 0.55)
        for st in G.get(c, []):
            out.append([(cx + px * h, y + py * h) for px, py in st])
        cx += gw * h + track * h
    return out
